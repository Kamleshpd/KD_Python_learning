'''
Assigment operator "="
'''
print("Assignment Operators")
print("--------------------")
x = 10 #(Assigns 10 to x)
print("x:",x)
x += 5 #(Equivalent to x = x + 5, so x becomes 15)
print("x+=5:",x)
x-= 3 #(Equivalent to x = x - 3)
print("x-=3:",x)
x *= 2 #(Equivalent to x = x * 2)
print("x*=2:",x)
x /= 4 #(Equivalent to x = x / 4)
print("x/=4:",x)
print("             ")